// Fetch circuit geometry from OpenStreetMap Overpass -> SVG paths (robust, retrying).
import { writeFileSync } from 'node:fs'

const TRACKS = [
  ['Belle Isle', 42.337, -82.997],
  ['Canadian Tire Motorsport Park', 44.052, -78.677],
  ['Daytona Road Course', 29.185, -81.07],
  ['Indianapolis Motor Speedway', 39.795, -86.235],
  ['Laguna Seca', 36.584, -121.753],
  ['Long Beach Street Circuit', 33.766, -118.189],
  ['Road America', 43.798, -87.989],
  ['Road Atlanta', 34.148, -83.816],
  ['Sebring International Raceway', 27.454, -81.348],
  ['Virginia International Raceway', 36.56, -79.207],
  ['Watkins Glen International', 42.337, -76.927],
]
const EP = 'https://overpass-api.de/api/interpreter'
const Q = (lat, lon) => `[out:json][timeout:120];(way["highway"="raceway"](around:6000,${lat},${lon}););out geom;`
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

async function overpass(q, tries = 5) {
  let lastErr
  for (let i = 0; i < tries; i++) {
    try {
      const res = await fetch(EP, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/x-www-form-urlencoded',
          'User-Agent': 'HCR-League-Site/1.0 (league track maps; zackdbrown03@gmail.com)',
          Accept: 'application/json',
        },
        body: 'data=' + encodeURIComponent(q),
      })
      if (!res.ok) { lastErr = new Error(res.status); await sleep(6000); continue }
      return await res.json()
    } catch (e) { lastErr = e; await sleep(6000) }
  }
  throw lastErr
}

function toPath(ways) {
  // ways = array of geometry arrays [{lat,lon}]. Project all together, one subpath each.
  const all = ways.flat()
  const latMean = all.reduce((s, c) => s + c.lat, 0) / all.length
  const k = Math.cos((latMean * Math.PI) / 180)
  const px = (c) => c.lon * k, py = (c) => -c.lat
  const xs = all.map(px), ys = all.map(py)
  const minX = Math.min(...xs), maxX = Math.max(...xs), minY = Math.min(...ys), maxY = Math.max(...ys)
  const w = maxX - minX || 1, h = maxY - minY || 1
  const scale = 1000 / Math.max(w, h), pad = 45
  const X = (c) => ((px(c) - minX) * scale + pad).toFixed(1)
  const Y = (c) => ((py(c) - minY) * scale + pad).toFixed(1)
  const vbW = Math.round(w * scale + pad * 2), vbH = Math.round(h * scale + pad * 2)
  let d = ''
  for (const g of ways) g.forEach((c, i) => { d += (i === 0 ? 'M' : 'L') + X(c) + ' ' + Y(c) })
  return { d, viewBox: `0 0 ${vbW} ${vbH}` }
}

const out = {}
for (const [name, lat, lon] of TRACKS) {
  try {
    const j = await overpass(Q(lat, lon))
    const ways = (j.elements || []).filter((e) => e.type === 'way' && e.geometry && e.geometry.length > 10)
    if (!ways.length) { console.log('NONE  ', name); await sleep(3500); continue }
    ways.sort((a, b) => b.geometry.length - a.geometry.length)
    // keep the main circuit + any ways that are a big fraction of it (skip tiny access roads)
    const main = ways[0].geometry.length
    const keep = ways.filter((w) => w.geometry.length >= Math.max(12, main * 0.15)).slice(0, 8)
    const { d, viewBox } = toPath(keep.map((w) => w.geometry))
    out[name] = { path: d, viewBox }
    console.log('OK    ', name, '-', keep.length, 'ways,', keep.reduce((s,w)=>s+w.geometry.length,0), 'pts')
  } catch (e) { console.log('ERR   ', name, String(e.message)) }
  await sleep(3500)
}

const ts = `// Auto-generated by scripts/fetch-track-maps.mjs — circuit outlines from OpenStreetMap (© OpenStreetMap contributors, ODbL).
export interface TrackMap { path: string; viewBox: string }
export const TRACK_MAPS: Record<string, TrackMap> = ${JSON.stringify(out, null, 2)}
`
writeFileSync('src/lib/trackMaps.ts', ts)
console.log('\nwrote ' + Object.keys(out).length + ' maps')
